KANJI_DIGITS = {"〇": 0, "一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}
DIGIT_KANJI = "〇一二三四五六七八九"


def _under10000(n):
    out = ""
    for place, ch in ((1000, "千"), (100, "百"), (10, "十")):
        d, n = divmod(n, place)
        if d:
            out += (DIGIT_KANJI[d] if d > 1 else "") + ch
    if n:
        out += DIGIT_KANJI[n]
    return out


def int_to_kanji(n):
    if n == 0:
        return "〇"
    if n >= 10000:
        man, rest = divmod(n, 10000)
        return _under10000(man) + "万" + (_under10000(rest) if rest else "")
    return _under10000(n)


